// The launcher (prefix+a): find a place, then start an agent or a shell there,
// resume a past session, or open a branch's worktree. Replaces herdr-launch's
// terminal popup. How it works and what's still missing: docs/herdr-flat.md,
// "Launcher".
//
// One ranked list of places on the left: open spaces, spaces closed lately,
// zoxide folders, folders from a shallow scan of ~, and folders past sessions
// ran in. The panel on the right shows the selected place: its git state,
// agents running there, its last sessions and its branches. → enters the
// panel, ← leaves it. Enter starts the agent in the chip (Tab cycles it, kept
// per folder; agents.json lists them), Shift+Enter a shell, Ctrl+Enter goes to
// the place's open space. An open place gets a new tab; anything else a space.

